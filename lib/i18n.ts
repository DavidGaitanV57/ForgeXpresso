const TABLES: Record<Locale, Dict> = {
  es: { ...es, ...LANDING.es },
  en: { ...en, ...LANDING.en },
  fr: { ...fr, ...LANDING.fr },
};

let current: Locale = "es";

export function detectDeviceLocale(navLang?: string): Locale {
  const raw = (navLang || (typeof navigator !== "undefined" ? navigator.language : "es") || "es").toLowerCase();
  if (raw.startsWith("fr")) return "fr";
  if (raw.startsWith("en")) return "en";
  if (raw.startsWith("es")) return "es";
  return "en";
}

export function getLocale(): Locale {
  return current;
}

export function loadStoredLocale(): Locale | null {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === "es" || v === "en" || v === "fr") return v;
  } catch {}
  return null;
}

export function initLocale(): Locale {
  current = loadStoredLocale() ?? detectDeviceLocale();
  return current;
}

export function setLocale(locale: Locale) {
  current = locale;
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {}
  if (typeof document !== "undefined") {
    document.documentElement.lang = locale;
  }
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const table = TABLES[current] || es;
  let s = table[key] ?? TABLES.es[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/** Apply data-i18n / data-i18n-html / data-i18n-placeholder / data-i18n-aria / data-i18n-title on a root. */
export function applyDomI18n(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (key) el.innerHTML = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key && "placeholder" in el) (el as HTMLInputElement).placeholder = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key) el.setAttribute("aria-label", t(key));
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) el.setAttribute("title", t(key));
  });
}

export function langSwitcherHTML(id = "langSw"): string {
  const buttons = LOCALES.map(
    (l) => `<button type="button" data-locale="${l.id}" class="${current === l.id ? "on" : ""}" title="${l.native}">${l.id.toUpperCase()}</button>`,
  ).join("");
  return `<div class="langsw${id === "introLang" ? " langsw-fixed" : ""}" id="${id}" role="group" aria-label="${t("intro.lang")}">${buttons}</div>`;
}
